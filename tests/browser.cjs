const assert = require('node:assert/strict');
const { chromium } = require('playwright');
const path = require('node:path');
const fs = require('node:fs');
const artifacts = process.env.TEST_ARTIFACT_DIR || process.env.JCODE_SCRATCH_DIR || require('node:os').tmpdir();
fs.mkdirSync(artifacts, { recursive: true });

(async () => {
  const browser = await chromium.launch({ headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  const url = process.env.TEST_URL || 'http://127.0.0.1:5000';
  await page.goto(url);
  await page.waitForFunction(() => document.querySelector('#options-status').textContent.includes('county options loaded'));
  assert.equal(await page.locator('#county').inputValue(), 'Los Angeles');
  assert.equal(await page.locator('#infrastructure-fields input').count(), 13);
  await page.locator('#predict-button').click();
  await page.waitForFunction(() => document.querySelector('#result-badge').textContent === 'MODEL OUTPUT', null, { timeout: 60000 });
  assert.equal(await page.locator('.probability-row').count(), 4);
  assert.match(await page.locator('.severity-output h3').textContent(), /Minor|Moderate|Serious|Severe/);
  await page.screenshot({ path: path.join(artifacts, 'trafficlens-desktop.png'), fullPage: true });
  await page.locator('#demo-button').click();
  assert.equal(await page.locator('#weather_condition').inputValue(), 'Rain');
  await page.locator('#predict-button').click();
  await page.waitForFunction(() => document.querySelector('#result-badge').textContent === 'MODEL OUTPUT', null, { timeout: 60000 });
  await page.locator('button[type="reset"]').click();
  assert.equal(await page.locator('#county').inputValue(), 'Los Angeles');
  assert.equal(await page.locator('#result-badge').textContent(), 'AWAITING INPUT');
  await page.locator('#county').fill('Not A County');
  await page.locator('#predict-button').click();
  await page.locator('#form-error').waitFor({ state: 'visible' });
  assert.match(await page.locator('#form-error').textContent(), /county/);
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('button[type="reset"]').click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  await page.screenshot({ path: path.join(artifacts, 'trafficlens-mobile.png'), fullPage: true });
  assert.deepEqual(errors, []);
  console.log('PASS: county options, default and demo real predictions, probabilities, reset, API error, mobile layout, and no JS errors');
  await browser.close();
})().catch(error => { console.error(error); process.exit(1); });
